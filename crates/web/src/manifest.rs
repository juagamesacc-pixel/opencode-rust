/// All pages belonging to `locale`, in source-tree order.
pub fn pages_for_locale(locale: &str) -> Vec<&'static Page> {
    PAGES.iter().filter(|page| page.locale == locale).collect()
}

/// Look up a single page by locale and slug.
pub fn find(locale: &str, slug: &str) -> Option<&'static Page> {
    PAGES
        .iter()
        .find(|page| page.locale == locale && page.slug == slug)
}

/// Every distinct slug in the collection, in source-tree order and de-duplicated.
pub fn slugs() -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for page in PAGES.iter() {
        if !out.contains(&page.slug) {
            out.push(page.slug);
        }
    }
    out
}

/// Page count for `locale`, or `0` when the locale ships no pages.
pub fn count_for_locale(locale: &str) -> usize {
    LOCALE_PAGE_COUNTS
        .iter()
        .find(|(name, _)| *name == locale)
        .map(|(_, count)| *count)
        .unwrap_or(0)
}
