pub struct Page {
    /// Locale directory name in the source tree; `root` is the untranslated English copy.
    pub locale: &'static str,
    /// Starlight entry id: the `.mdx` file name without its extension.
    pub slug: &'static str,
    /// Verbatim `title:` frontmatter value.
    pub title: &'static str,
    /// Verbatim `description:` frontmatter value.
    pub description: &'static str,
    /// Path of the copied `.mdx` file relative to the crate root.
    pub path: &'static str,
}

impl Page {
    /// `true` when this page is the untranslated English copy (`docs/<slug>.mdx`).
    pub fn is_default_locale(&self) -> bool {
        self.locale == crate::locales::DEFAULT_LOCALE
    }

    /// Starlight collection id, e.g. `config` for the default locale and `de/config` otherwise.
    pub fn entry_id(&self) -> String {
        if self.is_default_locale() {
            return self.slug.to_string();
        }
        format!("{}/{}", self.locale, self.slug)
    }

    /// Site route below the `/docs` base path; `index` collapses to the locale root.
    pub fn url_path(&self) -> String {
        if self.is_default_locale() {
            if self.slug == "index" {
                return "/docs/".to_string();
            }
            return format!("/docs/{}/", self.slug);
        }
        if self.slug == "index" {
            return format!("/docs/{}/", self.locale);
        }
        format!("/docs/{}/{}/", self.locale, self.slug)
    }
}

